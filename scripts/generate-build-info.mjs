// Generates src/app/core/build-info/build-info.values.generated.ts (gitignored) from
// package.json, the current git commit and today's UTC date. angular.json swaps it in for
// the committed placeholder (build-info.values.ts) via fileReplacements, so a fresh clone
// that never ran this script still type-checks, tests and lints; only `ng build` / `ng serve`
// need it, and npm's pre<script> hooks run it automatically.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/app/core/build-info/build-info.values.generated.ts');

function gitShortSha() {
  try {
    const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return /^[0-9a-f]{4,40}$/i.test(sha) ? sha : 'unknown';
  } catch {
    // git missing, or not a git checkout (e.g. a source tarball)
    return 'unknown';
  }
}

function buildDate() {
  // Honour SOURCE_DATE_EPOCH (seconds) for reproducible builds, else use now.
  const epoch = Number(process.env.SOURCE_DATE_EPOCH);
  const date = Number.isFinite(epoch) && epoch > 0 ? new Date(epoch * 1000) : new Date();
  return date.toISOString().slice(0, 10);
}

const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const info = { version: String(version), commit: gitShortSha(), date: buildDate() };

const contents = `// AUTO-GENERATED by scripts/generate-build-info.mjs. Do not edit; it is gitignored.
import type { BuildInfo } from './build-info';

export const BUILD_INFO_VALUES: BuildInfo = {
  version: '${info.version}',
  commit: '${info.commit}',
  date: '${info.date}',
};
`;

writeFileSync(outFile, contents);
console.log(`build-info: v${info.version} ${info.commit} ${info.date}`);
