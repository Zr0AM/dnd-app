// Generates src/app/core/build-info/build-info.values.generated.ts (gitignored) from
// the current git commit and a build number. angular.json swaps it in for
// the committed placeholder (build-info.values.ts) via fileReplacements, so a fresh clone
// that never ran this script still type-checks, tests and lints; only `ng build` / `ng serve`
// need it, and npm's pre<script> hooks run it automatically.
//
// Build number: "<UTC date>_<run>", e.g. 2026-10-01_042, where <run> is the run number of the
// GitHub Actions "Build" workflow for the commit:
//   1. GITHUB_RUN_NUMBER, when set (the build runs inside GitHub Actions);
//   2. else, on a Cloudflare Pages build (CF_PAGES_COMMIT_SHA set; Pages builds through its own
//      Git integration, outside Actions), the run number looked up from the public GitHub API
//      for that commit, falling back to 000 with a warning if that fails (never fails the build);
//   3. else (a local build) the literal suffix "dev", e.g. 2026-10-01_dev.
// package.json's version stays the semantic version but is not displayed.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  formatBuildNumber,
  lookupRunNumber,
  parseRunNumber,
  resolveBuildDate,
} from './build-number.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/app/core/build-info/build-info.values.generated.ts');

const SHA_PATTERN = /^[0-9a-f]{4,40}$/i;

function gitShortSha() {
  try {
    const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (SHA_PATTERN.test(sha)) {
      return sha;
    }
  } catch {
    // git missing, or not a git checkout (e.g. a source tarball)
  }
  const pagesSha = (process.env.CF_PAGES_COMMIT_SHA ?? '').trim();
  return SHA_PATTERN.test(pagesSha) ? pagesSha.slice(0, 7) : 'unknown';
}

async function runPart() {
  const actionsRun = parseRunNumber(process.env.GITHUB_RUN_NUMBER);
  if (actionsRun !== null) {
    return actionsRun;
  }

  const pagesSha = (process.env.CF_PAGES_COMMIT_SHA ?? '').trim();
  if (pagesSha === '') {
    return 'dev';
  }
  if (!SHA_PATTERN.test(pagesSha)) {
    console.warn(
      'build-info: warning: CF_PAGES_COMMIT_SHA is not a commit hash; using build run 000',
    );
    return 0;
  }
  const { runNumber, error } = await lookupRunNumber({
    sha: pagesSha,
    token: process.env.GITHUB_TOKEN,
  });
  if (runNumber === null) {
    console.warn(
      `build-info: warning: could not look up the GitHub Actions run number for ${pagesSha.slice(0, 7)} ` +
        `(${error}); using build run 000`,
    );
    return 0;
  }
  return runNumber;
}

const info = {
  commit: gitShortSha(),
  build: formatBuildNumber(resolveBuildDate(process.env.SOURCE_DATE_EPOCH), await runPart()),
};

const contents = `// AUTO-GENERATED by scripts/generate-build-info.mjs. Do not edit; it is gitignored.
import type { BuildInfo } from './build-info';

export const BUILD_INFO_VALUES: BuildInfo = {
  commit: ${JSON.stringify(info.commit)},
  build: ${JSON.stringify(info.build)},
};
`;

writeFileSync(outFile, contents);
console.log(`build-info: ${info.build} ${info.commit}`);
